// renderPlugins is the shared PLUGINS-artifact renderer.
// / renderPlugins 是共享的 PLUGINS 产物渲染器。
func renderPlugins(r pluginsRender) string {
	all := plugins.All()
	credNames := map[string]bool{}
	for _, n := range credential.Authenticators() {
		credNames[n] = true
	}

	identify := 0
	credential := 0
	for _, p := range all {
		m := p.Modes()
		if m&plugins.ModeIdentify != 0 {
			identify++
		}
		if m&plugins.ModeCredential != 0 || credNames[p.Name()] {
			credential++
		}
	}

	var b strings.Builder
	b.WriteString(generatedBanner)
	b.WriteString("# Plugins\n\n")
	if r.twinLink != "" {
		b.WriteString(r.twinLink)
		b.WriteString("\n\n")
	}
	b.WriteString(r.intro(len(all), identify, credential))

	b.WriteString("| " + strings.Join(r.headers[:], " | ") + " |\n")
	b.WriteString("|---|---|---|---|\n")
	for _, p := range all {
		m := p.Modes()
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n",
			p.Name(), cellPorts(p.Ports()), cellBit(m, plugins.ModeIdentify),
			cellBool(credNames[p.Name()] || m&plugins.ModeCredential != 0))
	}
	return b.String()
}

// cellPorts renders a sorted, comma-joined port list.
// / cellPorts 渲染排序后逗号连接的端口列表。
func cellPorts(ports []int) string {
	sorted := make([]int, len(ports))
	copy(sorted, ports)
	sort.Ints(sorted)
	parts := make([]string, 0, len(sorted))
	for _, p := range sorted {
		parts = append(parts, fmt.Sprintf("%d", p))
	}
	return strings.Join(parts, ", ")
}

// cellBit renders a Mode capability bit as a check mark or a dash.
// / cellBit 把 Mode 能力位渲染成对勾或短横。
func cellBit(m, bit plugins.Mode) string {
	return cellBool(m&bit != 0)
}

// cellBool renders a capability as a check mark or a dash.
// / cellBool 把能力渲染成对勾或短横。
func cellBool(ok bool) string {
	if ok {
		return "✅"
	}
	return "–"
}
